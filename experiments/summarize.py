#!/usr/bin/env python
"""Build results/summary.md from the CSV files (mean ± std over seeds,
paired differences against ADR).  The README and the report quote this
file; no number is typed by hand.

Run: python experiments/summarize.py
"""

from __future__ import annotations

import csv
import json
import math
from pathlib import Path

import numpy as np

from common import RESULTS, fmt_ms, mean_std, read_rows
from netsim.config import SCENARIOS

OUT = RESULTS / "summary.md"
ORDER = ["Fixed-SF7", "Fixed-SF12", "ADR", "ML-HGB", "Triggered-Rules", "LLM-Agent",
         "LLM-Agent-noAnomalyTool", "LLM-Agent-noFacts", "Oracle"]
NAMES = {"s1_jamming": "S1 jamming", "s2_deep_fade": "S2 deep fade", "s3_pass_end": "S3 pass end",
         "s4_gateway_outage": "S4 gateway outage", "s5_traffic_surge": "S5 traffic surge"}


def label(r: dict) -> str:
    """Policy label; LLM rows carry their model so several models can coexist."""
    mk = r.get("model_key", "-")
    return r["policy"] if mk in ("-", "", None) or (isinstance(mk, float) and math.isnan(mk)) \
        else f"{r['policy']} [{mk}]"


def ordered(rows: list[dict]) -> list[str]:
    labs = {label(r) for r in rows}
    return sorted(labs, key=lambda l: (ORDER.index(l.split(" [")[0]) if l.split(" [")[0] in ORDER else 99, l))


def table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def read_csv(p: Path) -> list[dict]:
    with p.open() as f:
        return list(csv.DictReader(f))


def paired(rows: list[dict], scen: str, pol: str, key: str, ref: str = "ADR") -> str:
    a = {r["seed"]: r[key] for r in rows if r["scenario"] == scen and label(r) == pol}
    b = {r["seed"]: r[key] for r in rows if r["scenario"] == scen and label(r) == ref}
    d = [a[s] - b[s] for s in a if s in b and not (math.isnan(a[s]) or math.isnan(b[s]))]
    if not d:
        return "n/a"
    m, s, n = mean_std(d)
    wins = sum(1 for x in d if x > 0)
    return f"{m*100:+.1f} ± {s*100:.1f} pts ({wins}/{n} seeds better)"


def main() -> None:
    parts = ["# Results summary (generated by experiments/summarize.py — do not edit)\n"]

    p = RESULTS / "e1a_thresholds.csv"
    if p.exists():
        r = read_csv(p)
        parts.append("## E1a — ideal receiver vs Semtech thresholds (20-byte packet, AWGN)\n")
        parts.append(table(["SF", "Semtech threshold (dB)", "SNR for PER 1 % (dB)", "gap (dB)",
                            "SNR for PER 10 % (dB)"],
                           [[x["sf"], x["semtech_threshold_db"], x["snr_per1pct_analytic_db"],
                             x["gap_per1pct_vs_threshold_db"], x["snr_per10pct_analytic_db"]] for x in r]))
        mc = read_csv(RESULTS / "e1a_ser_vs_snr_awgn.csv")
        dev = [abs(float(x["ser_mc"]) - float(x["ser_analytic"])) for x in mc]
        parts.append(f"\nMonte Carlo vs exact SER: max absolute difference {max(dev):.4f} over "
                     f"{len(mc)} points ({mc[0]['n_trials']} trials each).\n")
    p = RESULTS / "e1b_critical_rate.csv"
    if p.exists():
        r = read_csv(p)
        parts.append("## E1b — Doppler rate at which PER exceeds 10 % (SNR_req + 5 dB)\n")
        sfs = sorted({x["sf"] for x in r}, key=int)
        parts.append(table(["receiver"] + [f"SF{s}" for s in sfs],
                           [[rx] + [next(x["critical_rate_hz_s"] for x in r if x["receiver"] == rx and x["sf"] == s)
                                    for s in sfs] for rx in ("preamble", "tracking")]))
        parts.append("\nValues are the first grid point (Hz/s) with PER > 10 %; '>1000' = never on the grid.\n")

    p = RESULTS / "e2b_altitude_sweep.csv"
    if p.exists():
        r = read_csv(p)
        e2 = read_csv(RESULTS / "e2_satellite_pass.csv")
        rates = [abs(float(x["doppler_rate_hz_s"])) for x in e2]
        parts.append("## E2 — 600 km zenith pass\n")
        parts.append(f"- pass above 10°: {len(e2) - 1} s; max |Doppler| {max(abs(float(x['doppler_hz'])) for x in e2):.0f} Hz; "
                     f"max |Doppler rate| {max(rates):.1f} Hz/s; LOS SNR from "
                     f"{min(float(x['snr_los_db']) for x in e2):.1f} to {max(float(x['snr_los_db']) for x in e2):.1f} dB; "
                     f"delay {min(float(x['delay_ms']) for x in e2):.2f}–{max(float(x['delay_ms']) for x in e2):.2f} ms.\n")
        rows = []
        for rx in ("preamble", "tracking"):
            for sf in ("10", "11", "12"):
                sel = [x for x in r if x["receiver"] == rx and x["sf"] == sf]
                rows.append([rx, f"SF{sf}"] + [f"{float(x['feasible_share']):.2f}" for x in sel])
        alts = [x["altitude_km"] for x in r if x["receiver"] == "tracking" and x["sf"] == "12"]
        parts.append("Share of a zenith pass with PER ≤ 1 % (LOS, 14 dBm):\n")
        parts.append(table(["receiver", "SF"] + [f"{a} km" for a in alts], rows) + "\n")

    p = RESULTS / "e3_scalability.csv"
    if p.exists():
        r = read_rows(p)
        a = RESULTS / "e3_aloha_check.csv"
        parts.append("## E3 — scalability (terrestrial cell, no anomaly, 2 h, 5 seeds)\n")
        ns = sorted({x["n_devices"] for x in r})
        rows = []
        for pol in ordered(r):
            sel = [x for x in r if label(x) == pol]
            if not sel:
                continue
            rows.append([pol] + [fmt_ms([x["pdr"] for x in sel if x["n_devices"] == n], 100, 1) for n in (ns[0], ns[-1])]
                        + [fmt_ms([x["energy_per_delivered_mj"] for x in sel if x["n_devices"] == n], 1, 1) for n in (ns[0], ns[-1])])
        parts.append(table(["policy", f"PDR % N={ns[0]}", f"PDR % N={ns[-1]}",
                            f"mJ/delivered N={ns[0]}", f"mJ/delivered N={ns[-1]}"], rows))
        if a.exists():
            al = read_rows(a)
            err = max(abs(x["S_sim"] - x["S_theory"]) for x in al)
            parts.append(f"\nALOHA check: max |S_sim − G·e^(−2G)| = {err:.4f} for G up to {max(x['G'] for x in al):.2f}.\n")

    p = RESULTS / "e4_summary.csv"
    if p.exists():
        r = read_rows(p)
        parts.append("## E4 — anomaly scenarios (3 h, N = 300, event at t = 1 h, 5 seeds)\n")
        parts.append("PDR in the event window [start, end + 10 min] (mean ± std, %):\n")
        pols = ordered(r)
        parts.append(table(["policy"] + [NAMES[s] for s in SCENARIOS],
                           [[pol] + [fmt_ms([x["pdr_event"] for x in r if x["scenario"] == s and label(x) == pol], 100, 1)
                                     for s in SCENARIOS] for pol in pols]))
        parts.append("\nEnergy per delivered packet in the event window (mJ):\n")
        parts.append(table(["policy"] + [NAMES[s] for s in SCENARIOS],
                           [[pol] + [fmt_ms([x["energy_per_delivered_event_mj"] for x in r if x["scenario"] == s and label(x) == pol], 1, 1)
                                     for s in SCENARIOS] for pol in pols]))
        parts.append("\nRecovery time (min): mean over recovered seeds, [number of seeds not recovered "
                     "within event end + 1 h]:\n")
        rows = []
        for pol in pols:
            line = [pol]
            for s in SCENARIOS:
                v = [x["recovery_time_s"] for x in r if x["scenario"] == s and label(x) == pol]
                ok = [x for x in v if not math.isnan(x)]
                line.append((f"{np.mean(ok)/60:.0f}" if ok else "–") + f" [{len(v) - len(ok)}]")
            rows.append(line)
        parts.append(table(["policy"] + [NAMES[s] for s in SCENARIOS], rows))
        parts.append("\nPaired difference in event-window PDR against ADR (same seeds, same channel realisations):\n")
        parts.append(table(["policy"] + [NAMES[s] for s in SCENARIOS],
                           [[pol] + [paired(r, s, pol, "pdr_event") for s in SCENARIOS]
                            for pol in pols if pol != "ADR"]))
        parts.append("\nWhole-run reading delivery ratio (delivered / generated readings, %):\n")
        parts.append(table(["policy"] + [NAMES[s] for s in SCENARIOS],
                           [[pol] + [fmt_ms([x["reading_delivery_ratio"] for x in r if x["scenario"] == s and label(x) == pol], 100, 1)
                                     for s in SCENARIOS] for pol in pols]))
        det = [x for x in r if x["policy"] == "ADR"]
        parts.append("\nDetector (ADR runs): alert precision, event recall, mean detection delay:\n")
        parts.append(table(["scenario", "precision", "recall", "delay (min)"],
                           [[NAMES[s], fmt_ms([x["det_precision"] for x in det if x["scenario"] == s], 1, 2),
                             fmt_ms([x["det_recall"] for x in det if x["scenario"] == s], 1, 2),
                             fmt_ms([x["det_detection_delay_s"] for x in det if x["scenario"] == s], 1 / 60, 1)]
                            for s in SCENARIOS if s != "s3_pass_end"]))
        parts.append("\n(S3 is not scored: the end of a pass is known from the ephemeris and handled by the elevation trigger.)\n")

    p = RESULTS / "e5_agent_cost.csv"
    if p.exists():
        r = read_csv(p)
        parts.append("## E5 — cost of the agent\n")
        keys = ["model", "policy", "experiment", "runs", "decisions", "llm_calls_per_sim_hour", "tool_calls_per_decision",
                "decision_latency_median_s", "decision_latency_p95_s", "llm_call_latency_median_s",
                "set_calls", "set_rejected", "invalid_action_rate", "decisions_with_a_change",
                "unknown_or_malformed_calls", "rbw_violations", "fallbacks", "host"]
        parts.append(table(keys, [[x[k] for k in keys] for x in r]))
        parts.append("")

    p = RESULTS / "e6_summary.csv"
    if p.exists():
        r = read_rows(p) + [x for x in read_rows(RESULTS / "e4_summary.csv") if x["policy"] in ("ADR", "LLM-Agent")]
        parts.append("## E6 — ablations (event-window PDR, %)\n")
        pols = ordered(r)
        parts.append(table(["policy"] + [NAMES[s] for s in SCENARIOS],
                           [[pol] + [fmt_ms([x["pdr_event"] for x in r if x["scenario"] == s and label(x) == pol], 100, 1)
                                     for s in SCENARIOS] for pol in pols]))
        parts.append("")

    p = RESULTS / "ml" / "hgb_training.json"
    if p.exists():
        parts.append("## ML classifier training\n")
        parts.append("```json\n" + p.read_text() + "\n```\n")
    OUT.write_text("\n".join(parts) + "\n")
    print("  wrote", OUT.relative_to(RESULTS.parent))


if __name__ == "__main__":
    main()
